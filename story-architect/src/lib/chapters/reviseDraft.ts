/**
 * «Доработать черновик по заметкам автора».
 *
 * Автор пишет заметки в конце черновика, под заголовком из шаблонов редактора
 * («ЗАМЫСЕЛ И МЫСЛИ», «СЦЕНА», «ЗАМЕТКА О МИРЕ», «ДИАЛОГ») или под
 * «ЗАМЕТКИ ДЛЯ ДОРАБОТКИ». Всё до первого такого заголовка — проза главы,
 * всё после — заметки.
 */
import { AUTHOR_NOTES_MARKER } from "../authorIntent/prompt";
import { parseEditorMarks } from "./editorMarks";

export const NOTE_HEADINGS = [
  "ЗАМЫСЕЛ И МЫСЛИ",
  "СЦЕНА",
  "ЗАМЕТКА О МИРЕ",
  "ДИАЛОГ",
  "ЗАМЕТКИ ДЛЯ ДОРАБОТКИ",
] as const;

export const MAX_REVISE_CHARS = 60_000;

function isHeading(line: string): boolean {
  const cleaned = line
    .trim()
    .replace(/^[*#\s]+|[*#\s:]+$/g, "")
    .toUpperCase();
  return (NOTE_HEADINGS as readonly string[]).includes(cleaned);
}

export function splitDraftAndNotes(
  text: string
): { prose: string; notes: string } | null {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  const index = lines.findIndex(isHeading);
  if (index <= 0) return null;

  const prose = lines.slice(0, index).join("\n").trim();
  const notes = lines.slice(index).join("\n").trim();
  const hasBody = lines.slice(index + 1).some((line) => line.trim());
  if (!prose || !hasBody) return null;

  return { prose, notes };
}

export function buildReviseMessages(input: {
  projectName: string;
  chapterTitle: string;
  canon: string;
  storyState: string;
  prose: string;
  notes: string;
  hasMarks?: boolean;
}): { system: string; user: string } {
  const system = `Ты — AI Writer в системе Story Architect. Автор написал черновик главы и добавил в конце свои заметки. Твоя задача — аккуратно вплести заметки в текст главы.

ПРАВИЛА:
- Вноси ТОЛЬКО то, о чём сказано в заметках. Остальной текст сохраняй как есть: смысл, порядок событий, стиль, абзацы, имена.
- Не сокращай текст и не переписывай то, что заметки не затрагивают.
- Деталь из заметок вводи естественно, там, где она уместна по сюжету.
- Заметки автора — его решения. Но если заметка прямо противоречит Canon или состоянию истории, НЕ вноси эту часть, а опиши конфликт.
- Не раскрывай тайны, не добавляй крупных событий, которых нет в заметках.
- Верни только полный обновлённый текст главы, без заметок, без пояснений и без заголовков.${
    input.hasMarks
      ? `
- В тексте есть пометки автора вида [[ТИП: «фрагмент» — комментарий]]. Они перечислены с номерами в списке ПОМЕТКИ АВТОРА. Каждая пометка — прямое указание живого редактора, написанное быстро и неформально, с опечатками. Читай её по смыслу, а не по буквам, и применяй к указанному месту. Ни одну пометку нельзя пропустить.
  Как понимать комментарий:
  • Автор диктует формулировку («пусть говорит: — …», «лучше: …», «надо так: …») — используй его слова дословно, сохрани знаки препинания, обращение («вам», «тебя») и интонацию (восклицание, вопрос).
  • Автор указывает на ошибку или нелогичность («у аппарата нет голоса», «так не бывает», «повтор») — исправь сам фрагмент: убери или замени неверное слово или оборот. Нельзя оставлять его как есть, даже если вопрос не сформулирован как просьба. Подбери замену по смыслу сцены.
  • Автор называет желаемое действие или эффект («показать, как он расслабился, как возросла эмпатия…») — раскрой это в тексте полноценно, одним-двумя абзацами в стиле главы, а не одной фразой, и перечисли всё названное.
  • Автор называет слово, которое не нравится («не коктейль, а что-нибудь другое») — замени его во всех местах главы единообразно.
  • Комментарий справочный («Для инфо», описание внешности, референсы, сведения о мире) — НЕ вставляй в текст. Воспринимай как ограничения для всей главы (например, «не описывать итоговую внешность сразу») и соблюдай их.
  • Автор сомневается, но разрешает оставить («если нужно для текста, то норм») — оставь фрагмент как есть.
  • Автору нужен его собственный выбор из нескольких вариантов — оставь фрагмент без изменений и опиши вопрос в отчёте.
  Типы: КОММЕНТАРИЙ — пожелание к фрагменту; ВОПРОС — часто скрытая правка или замечание, читай комментарий как указание; ПЕРЕПИСАТЬ — перепиши фрагмент иначе по комментарию, сохранив смысл событий.
  Всё, что не названо в пометке, не меняй. В итоговом тексте пометок быть не должно: ни скобок [[ ]], ни слов КОММЕНТАРИЙ/ВОПРОС/ПЕРЕПИСАТЬ.
- Если в тексте были пометки, в самом конце ВСЕГДА добавь строку ${AUTHOR_NOTES_MARKER} и под ней отчёт: по одной строке на каждую пометку в формате «№: применено / оставлено / нужен твой выбор — что именно сделано и почему». Если были ещё и конфликты с Canon, опиши их после отчёта. Этот раздел не часть текста главы.`
      : ""
  }
- Если пометок нет, но были конфликты, в самом конце добавь строку ${AUTHOR_NOTES_MARKER}, затем краткое описание каждого конфликта. Этот раздел не часть текста главы.`;

  const marks = parseEditorMarks(input.prose);
  const marksList = marks.length
    ? `ПОМЕТКИ АВТОРА (применить все, ничего не пропускать):
${marks.map((m, i) => `${i + 1}. [${m.kind}] фрагмент «${m.fragment}» — ${m.comment}`).join("\n")}

`
    : "";

  const user = `Проект: ${input.projectName}
Глава: ${input.chapterTitle}

CANON FACTS:
${input.canon}

СОСТОЯНИЕ ИСТОРИИ:
${input.storyState}

${marksList}ТЕКСТ ГЛАВЫ:
${input.prose}

${
    input.notes
      ? `ЗАМЕТКИ АВТОРА, КОТОРЫЕ НУЖНО ВПЛЕСТИ:
${input.notes}`
      : "Заметок отдельным блоком нет: учти пометки автора в тексте."
  }`;

  return { system, user };
}
